// Refresh the bundled Inter faces without adding a runtime network dependency.
// Keep the font bytes in the render-blocking stylesheet so even a hard refresh
// cannot paint fallback text while waiting for a separate font request.
import fs from 'node:fs/promises';

const source = 'https://fonts.googleapis.com/css2?family=Inter:wght@400..700&display=swap';
async function download(url, options) {
  const response = await fetch(url, options);
  if (!response.ok) throw new Error(`${response.status} downloading ${url}`);
  return response;
}
let css = await (await download(source, { headers: {
  'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0.0.0 Safari/537.36',
} })).text();
const urls = [...new Set(css.match(/https:\/\/fonts\.gstatic\.com\/[^)]+\.woff2/g))];
if (!urls.length) throw new Error('Google Fonts did not return WOFF2 faces');
for (const url of urls) {
  const bytes = Buffer.from(await (await download(url)).arrayBuffer());
  if (bytes.toString('ascii', 0, 4) !== 'wOF2') throw new Error(`Invalid WOFF2: ${url}`);
  css = css.replaceAll(url, `data:font/woff2;base64,${bytes.toString('base64')}`);
}
css = css.replaceAll('font-display: swap', 'font-display: block');
await fs.writeFile(new URL('../public/fonts.css', import.meta.url),
  '/* Bundled Inter (SIL OFL 1.1; see Inter-OFL.txt). Generated by tools/bundle-fonts.mjs. */\n' +
  'html[data-fonts-loading] body { visibility: hidden; }\n' + css);
await fs.writeFile(new URL('../public/Inter-OFL.txt', import.meta.url),
  await (await download('https://raw.githubusercontent.com/rsms/inter/master/LICENSE.txt')).text());
console.log(`Bundled ${urls.length} Inter subsets (${Buffer.byteLength(css)} CSS bytes)`);
